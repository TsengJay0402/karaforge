"""The model registry: known weights, their sources, licences and checksums.

The data lives in ``registry.json`` next to this module and is generated by
``scripts/update_model_registry.py``, which pins every file to an immutable revision and
records its SHA-256.  Weights are never bundled with KaraForge; they are downloaded into
``$KARAFORGE_HOME/models`` on demand (see :mod:`karaforge.models.store`).
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from karaforge.errors import ModelError

ModelKind = Literal["separator", "asr", "aligner", "g2p", "vad", "support"]

_REGISTRY_FILE = Path(__file__).with_name("registry.json")


class ModelFile(BaseModel):
    """One downloadable file of a model."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    path: str
    """Location relative to the model's directory (POSIX separators)."""
    url: str
    size: int = Field(ge=0)
    sha256: str = Field(min_length=64, max_length=64)


class ModelSpec(BaseModel):
    """A set of files that together form one model."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    id: str
    kind: ModelKind
    title: str
    license: str
    """SPDX identifier of the weights' licence (or a short name when there is none)."""
    license_url: str
    homepage: str
    revision: str
    """Immutable upstream revision the files were taken from."""
    commercial_use: bool
    """Whether the licence allows commercial use.  ``False`` requires explicit acceptance."""
    directory: str | None = None
    """Directory under ``models/`` when several models must share one (defaults to ``id``)."""
    requires: tuple[str, ...] = ()
    """Other registry entries that must be installed alongside this one."""
    note_zh: str = ""
    note_en: str = ""
    files: tuple[ModelFile, ...]

    @property
    def total_size(self) -> int:
        """Download size in bytes."""
        return sum(file.size for file in self.files)

    @property
    def folder(self) -> str:
        """Name of the directory under ``models/`` that holds the files."""
        return self.directory or self.id


class _Registry(BaseModel):
    model_config = ConfigDict(extra="forbid")

    generated: str = ""
    models: list[ModelSpec] = Field(default_factory=list[ModelSpec])


@lru_cache(maxsize=1)
def load_registry() -> dict[str, ModelSpec]:
    """Load the registry, keyed by model id."""
    if not _REGISTRY_FILE.is_file():
        return {}
    parsed = _Registry.model_validate(json.loads(_REGISTRY_FILE.read_text(encoding="utf-8")))
    return {spec.id: spec for spec in parsed.models}


def get_model(model_id: str) -> ModelSpec:
    """Look up a model by id.

    Raises:
        ModelError: If the registry has no such model.
    """
    registry = load_registry()
    if model_id not in registry:
        raise ModelError(
            f"模型註冊表裡沒有「{model_id}」。",
            f"Unknown model: {model_id}",
            hint_zh="執行 `kf models list` 可以看到所有可用的模型。",
            hint_en="Run `kf models list` to see the available models.",
        )
    return registry[model_id]
